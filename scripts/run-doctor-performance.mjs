// `pnpm performance:doctor [--control]`: the isolated production gate behind
// `cli.doctor.p95-ms` (#6346). Same isolation as the stream and shell gates:
// allowlisted environment, synthetic state root, built production server owned
// by Playwright, evidence per invocation under artifacts/doctor-performance/.
//
// The CLI under measurement is the one `COVEN_BIN` names, which the workflow
// installs from the pinned release fixture; the launcher refuses to run without
// an absolute, existing binary rather than let the server discover whatever is
// on PATH. The positive control wraps that binary in a script that sleeps past
// the ceiling while a marker file exists, so the route's own timeout fires.
import { chmodSync, existsSync, statSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  assertIsolatedPerformanceBuild,
  buildBrowserPerformanceInvocation,
  launchPlaywright,
  prepareBrowserPerformanceInvocation,
} from "./browser-performance-launch.mjs";
import { doctorExecControlStallMs } from "../tests/fixtures/doctor-exec-performance.ts";

export function parseDoctorArguments(args) {
  if (args.length === 0) return { control: false };
  if (args.length === 1 && args[0] === "--control") return { control: true };
  throw new Error("Usage: pnpm performance:doctor [--control]; the workload cannot be overridden");
}

/** The binary the server will spawn: absolute, existing, a regular file. */
export function resolveCovenBinary(sourceEnv) {
  const candidate = typeof sourceEnv.COVEN_BIN === "string" ? sourceEnv.COVEN_BIN.trim() : "";
  if (!candidate || !path.isAbsolute(candidate)) {
    throw new Error("COVEN_BIN must name the absolute path of the pinned coven binary to measure");
  }
  if (!existsSync(candidate) || !statSync(candidate).isFile()) {
    throw new Error(`COVEN_BIN does not name an existing file: ${candidate}`);
  }
  return candidate;
}

/**
 * Source of the control wrapper. It sleeps synchronously past the ceiling only
 * while the marker exists, then runs the real binary with the same arguments
 * and exit code, so the clean trials in a control run measure the real CLI.
 */
export function controlWrapperSource({ realBinary, marker, stallMs }) {
  const runsUnderNode = /\.[cm]?js$/i.test(realBinary);
  return [
    "#!/usr/bin/env node",
    "// Generated by scripts/run-doctor-performance.mjs for one --control invocation.",
    "const { existsSync } = require('node:fs');",
    "const { spawnSync } = require('node:child_process');",
    `const MARKER = ${JSON.stringify(marker)};`,
    `const STALL_MS = ${Number(stallMs)};`,
    `const REAL = ${JSON.stringify(realBinary)};`,
    "if (existsSync(MARKER)) Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, STALL_MS);",
    runsUnderNode
      ? "const result = spawnSync(process.execPath, [REAL, ...process.argv.slice(2)], { stdio: 'inherit', env: process.env });"
      : "const result = spawnSync(REAL, process.argv.slice(2), { stdio: 'inherit', env: process.env });",
    "process.exit(result.status ?? 1);",
    "",
  ].join("\n");
}

export function buildDoctorInvocation({ sourceEnv, stateRoot, artifactRoot, control, covenBin, controlMarker }) {
  if (typeof covenBin !== "string" || !path.isAbsolute(covenBin)) {
    throw new Error("buildDoctorInvocation needs the absolute coven binary the server will spawn");
  }
  const env = {
    CAVE_DOCTOR_PERFORMANCE: "1",
    CAVE_DOCTOR_CONTROL: control ? "1" : "0",
    CAVE_DOCTOR_STATE_ROOT: stateRoot,
    CAVE_DOCTOR_ARTIFACT_ROOT: artifactRoot,
    // Explicit, never inherited from the allowlist: the server spawns exactly
    // this binary, and the invocation record names it.
    COVEN_BIN: covenBin,
  };
  if (control) env.CAVE_DOCTOR_CONTROL_MARKER = controlMarker;
  return buildBrowserPerformanceInvocation({
    sourceEnv, artifactRoot, spec: "tests/doctor-exec-performance.spec.ts", env,
  });
}

function reportedVersion(binary, home) {
  try {
    return execFileSync(binary, ["--version"], {
      encoding: "utf8", timeout: 30_000, env: { PATH: process.env.PATH ?? "", HOME: home, COVEN_HOME: path.join(home, ".coven") },
    }).trim().split("\n")[0];
  } catch (error) {
    return `unavailable: ${error instanceof Error ? error.message.split("\n")[0] : String(error)}`;
  }
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const { control } = parseDoctorArguments(process.argv.slice(2));
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  assertIsolatedPerformanceBuild(root);
  process.chdir(root);
  const realBinary = resolveCovenBinary(process.env);
  const { artifactRoot, stateRoot } = prepareBrowserPerformanceInvocation({
    root, gate: "doctor-performance", record: { control, covenBin: realBinary },
  });
  const covenVersion = reportedVersion(realBinary, path.join(stateRoot, "home"));
  let covenBin = realBinary;
  let controlMarker;
  if (control) {
    controlMarker = path.join(stateRoot, "doctor-control.stall");
    covenBin = path.join(stateRoot, "doctor-control-wrapper.js");
    writeFileSync(covenBin, controlWrapperSource({
      realBinary, marker: controlMarker, stallMs: doctorExecControlStallMs("doctor"),
    }));
    chmodSync(covenBin, 0o755);
  }
  // Add what the record could not know before the state root existed.
  const recordPath = path.join(artifactRoot, "invocation.json");
  const { readFileSync } = await import("node:fs");
  const record = JSON.parse(readFileSync(recordPath, "utf8"));
  Object.assign(record, { covenVersion, spawnedBinary: covenBin, controlMarker: controlMarker ?? null });
  writeFileSync(recordPath, JSON.stringify(record, null, 2));
  const invocation = buildDoctorInvocation({
    sourceEnv: process.env, stateRoot, artifactRoot, control, covenBin, controlMarker,
  });
  console.log(`Doctor exec performance evidence: ${artifactRoot}`);
  await launchPlaywright(invocation);
}
